import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

// In the monorepo, icons.meta.json is in the sibling packages/icons/dist
const metadataPath = path.resolve(__dirname, '../../../packages/icons/dist/icons.meta.json');

if (!fs.existsSync(metadataPath)) {
  console.error('❌ icons.meta.json not found. Run `pnpm --filter stera-icons build` first.');
  process.exit(1);
}

const metadata = JSON.parse(fs.readFileSync(metadataPath, 'utf8'));

// Group metadata entries by base icon name (componentName)
const iconGroups = new Map();

metadata.forEach(entry => {
  const { componentName, name: kebabName, weight, duotone, tags, variantComponentName, fileName, versionAdded, versionLastModified } = entry;

  if (!iconGroups.has(componentName)) {
    iconGroups.set(componentName, {
      name: componentName,
      kebabName,
      tags: new Set(),
      weights: new Set(),
      supportsDuotone: false,
      variants: {},
    });
  }

  const group = iconGroups.get(componentName);
  group.weights.add(weight);

  if (duotone) {
    group.supportsDuotone = true;
  }

  // Build variant key
  const variantKey = duotone ? `${weight}-duotone` : weight;
  if (!group.variants[variantKey]) {
    group.variants[variantKey] = {
      version: versionAdded,
      componentName: variantComponentName,
      fileName: fileName?.replace('.tsx', ''),
    };
  }

  if (tags && Array.isArray(tags)) {
    tags.forEach(tag => group.tags.add(tag));
  }
});

// Build result array
const icons = [];
iconGroups.forEach(group => {
  group.tags.add(group.name);
  icons.push({
    name: group.name,
    kebabName: group.kebabName,
    componentName: group.name,
    tags: Array.from(group.tags),
    weights: Array.from(group.weights).sort(),
    supportsDuotone: group.supportsDuotone,
    variants: group.variants,
  });
});

console.log(`📦 Processed ${icons.length} icons from metadata`);

// Ensure output directory exists
const dataDir = path.resolve(__dirname, '../data');
if (!fs.existsSync(dataDir)) {
  fs.mkdirSync(dataDir, { recursive: true });
}

// Write icons.json
const iconsJsonPath = path.join(dataDir, 'icons.json');
fs.writeFileSync(iconsJsonPath, JSON.stringify(icons, null, 2));
console.log(`✅ Generated ${iconsJsonPath}`);

// Generate icon-components.tsx (static icon map)
const mappingEntries = icons.map(icon =>
  `  '${icon.kebabName}': Icons.${icon.componentName}`
);

const componentsContent = `// Auto-generated by generate-icons.mjs - DO NOT EDIT
'use client';

import * as Icons from 'stera-icons/dynamic-variants';
import type { IconProps } from 'stera-icons';

export type DynamicVariantProps = IconProps & {
  weight?: 'regular' | 'bold' | 'fill';
  duotone?: boolean;
};

// eslint-disable-next-line @typescript-eslint/no-explicit-any
export const iconMap: Record<string, React.ComponentType<any>> = {
${mappingEntries.join(',\n')}
};
`;

const componentsPath = path.join(dataDir, 'icon-components.tsx');
fs.writeFileSync(componentsPath, componentsContent);
console.log(`✅ Generated ${componentsPath} with ${icons.length} entries`);
